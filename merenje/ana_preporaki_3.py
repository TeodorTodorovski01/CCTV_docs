#!/usr/bin/env python3
"""
collect_metrics.py

Data-collection script for the "Empirical Capacity Planning and Predictive
Workload Modeling" study (network-camera variant: phones used as RTSP/HTTP
IP cameras instead of USB webcams).

Design goals vs. the original script:
  - Supports 1-4 simultaneous camera streams (not hardcoded to one).
  - Logs the independent variables of the study as columns on every row
    (run_id, camera count, target resolution, target fps, motion label),
    so runs can be concatenated into one master CSV and modeled directly
    with the variable table in the proposal (N, W x H, FPS, mu).
  - Adds the dependent-variable metrics that were previously missing:
      * RAM resident set size (this process) + swap usage (not just
        "RAM used" system-wide)
      * Kernel interrupt count delta (/proc/interrupts) as an IRQ overhead
        proxy (replaces the USB-bus-specific IRQ idea, since the workload
        is now network-attached, not USB-attached)
      * iowait % (from /proc/stat) and disk write throughput/IOPS
        (from /proc/diskstats) for the storage subsystem
      * Network throughput (RX/TX bytes/s) and RX errors/drops per
        interface, which is the network-camera analogue of "USB bus
        saturation" in the original proposal
      * Per-camera capture latency (wall-clock time spent in .grab())
      * Frame loss rate (drops / (drops + frames)), not just a raw
        drop counter
  - Uses cap.grab() instead of cap.read() for the capture loop: grab()
    only demuxes/receives a frame from the stream, it does not decode it
    to a pixel array. Since this script never inspects frame content
    (no motion analysis, no recording), decoding every frame with
    read()/retrieve() was pure wasted CPU -- avoiding it matters a lot
    once you're running 4 concurrent 1080p streams.
  - Scene activity (mu / motion_label) can't be generated by software when
    it's a physically staged scene, so it's accepted as a required CLI
    argument and stamped on every row instead of being silently absent.

Usage:
    python3 data_collector.py \
        --cameras rtsp://192.168.100.108:8080/h264_aac.sdp\
        --run-id N2_720p_30fps_dynamic \
        --target-resolution 1280x720 \
        --target-fps 30 \
        --motion-label static \
        --duration-min 30 \
        --output test1.csv\

    # Quick local test without real cameras (uses your webcam / a test pattern):
    python3 collect_metrics.py --mock --duration-min 1 --output test.csv
"""

import argparse
import csv
import os
import re
import subprocess
import threading
import time
from datetime import datetime

import cv2
import psutil

os.environ["OPENCV_FFMPEG_CAPTURE_OPTIONS"] = (
    "rtsp_transport;udp|fflags;nobuffer|flags;low_delay"
)


# ============================================================
# THREADED CAMERA (per-stream capture + per-frame latency)
# ============================================================

class ThreadedCamera:
    """
    Reads timing/arrival metadata from the stream WITHOUT decoding frames.

    This script never looks at pixel data (no motion analysis, no saving
    video), so calling cv2.VideoCapture.read() -- which grabs AND decodes
    every frame to a raw BGR array -- burns CPU for nothing. We use
    .grab() instead, which only demuxes/receives the next frame from the
    stream and skips the decode step (.retrieve()). This keeps FPS,
    latency, and drop measurements accurate (they depend on frame
    arrival, not frame content) while cutting CPU usage substantially,
    which matters a lot with 4 concurrent 1080p streams.
    """

    def __init__(self, url, mock=False):
        self.url = url
        self.mock = mock
        self.running = True
        self.ret = False

        self.frames = 0
        self.drops = 0
        self.fps = 0.0
        self.last_fps_calc = time.time()

        self.last_latency_ms = 0.0
        self._latency_sum_window = 0.0
        self._latency_n_window = 0

        if mock:
            self.cap = cv2.VideoCapture(0)  # local webcam / test device
        elif url.startswith(("rtsp://", "http://")):
            self.cap = cv2.VideoCapture(url, cv2.CAP_FFMPEG)
            self.cap.set(cv2.CAP_PROP_BUFFERSIZE, 1)
        else:
            self.cap = cv2.VideoCapture(url)

        self.width = int(self.cap.get(cv2.CAP_PROP_FRAME_WIDTH))
        self.height = int(self.cap.get(cv2.CAP_PROP_FRAME_HEIGHT))
        self.resolution = f"{self.width}x{self.height}"

        self.thread = threading.Thread(target=self.update, daemon=True)
        self.thread.start()

    def update(self):
        while self.running:
            t0 = time.time()
            ret = self.cap.grab()  # demux/receive only -- no decode
            latency_ms = (time.time() - t0) * 1000.0

            if ret:
                self.ret = True
                self.frames += 1
                self._latency_sum_window += latency_ms
                self._latency_n_window += 1
            else:
                self.drops += 1

    def pop_window_stats(self):
        """Compute fps + mean capture latency since last call, then reset window."""
        now = time.time()
        elapsed = now - self.last_fps_calc
        if elapsed >= 1:
            self.fps = round(self.frames / elapsed, 2)
            self.frames = 0
            self.last_fps_calc = now

        if self._latency_n_window:
            self.last_latency_ms = round(
                self._latency_sum_window / self._latency_n_window, 2
            )
        self._latency_sum_window = 0.0
        self._latency_n_window = 0

        return self.fps, self.last_latency_ms

    def frame_loss_rate(self):
        total = self.frames + self.drops
        if total == 0:
            return 0.0
        return round(self.drops / total, 4)

    def stop(self):
        self.running = False
        self.cap.release()


# ============================================================
# SYSTEM METRIC HELPERS
# ============================================================

def temperature_c():
    try:
        with open("/sys/class/thermal/thermal_zone0/temp") as f:
            return round(int(f.read()) / 1000, 2)
    except Exception:
        return None


def cpu_freq_mhz():
    try:
        f = psutil.cpu_freq()
        return round(f.current, 1) if f else None
    except Exception:
        return None


def throttle_state():
    try:
        r = subprocess.check_output(["vcgencmd", "get_throttled"])
        return r.decode().strip()
    except Exception:
        return "N/A"


def process_rss_mb():
    try:
        return round(psutil.Process(os.getpid()).memory_info().rss / (1024 * 1024), 2)
    except Exception:
        return None


class DiskIRQNetSampler:
    """
    Tracks delta-based metrics that require two /proc reads a fixed
    interval apart: disk write throughput/IOPS, IRQ counts, iowait %,
    and per-interface network throughput/errors.
    """

    def __init__(self, disk_device_prefix="mmcblk", net_iface=None):
        self.disk_device_prefix = disk_device_prefix
        self.net_iface = net_iface or self._guess_iface()

        self._last_disk = self._read_diskstats()
        self._last_irq_total = self._read_irq_total()
        self._last_cpu_times = self._read_cpu_times()
        self._last_net = self._read_net_dev()
        self._last_t = time.time()

    def _guess_iface(self):
        # Prefer wlan0, then eth0, else first non-loopback interface found.
        try:
            with open("/proc/net/dev") as f:
                ifaces = [
                    line.split(":")[0].strip()
                    for line in f.readlines()[2:]
                    if ":" in line
                ]
            for pref in ("wlan0", "eth0"):
                if pref in ifaces:
                    return pref
            for i in ifaces:
                if i != "lo":
                    return i
        except Exception:
            pass
        return "wlan0"

    def _read_diskstats(self):
        stats = {}
        try:
            with open("/proc/diskstats") as f:
                for line in f:
                    parts = line.split()
                    dev = parts[2]
                    if self.disk_device_prefix in dev:
                        # fields: reads_completed(3) ... sectors_written(9) ... ms_writing(10)
                        stats[dev] = {
                            "writes_completed": int(parts[7]),
                            "sectors_written": int(parts[9]),
                        }
        except Exception:
            pass
        return stats

    def _read_irq_total(self):
        total = 0
        try:
            with open("/proc/interrupts") as f:
                for line in f.readlines():
                    nums = re.findall(r"\b\d+\b", line)
                    if nums and ":" in line.split()[0]:
                        total += sum(int(n) for n in nums)
        except Exception:
            pass
        return total

    def _read_cpu_times(self):
        try:
            with open("/proc/stat") as f:
                line = f.readline()
            vals = [int(x) for x in line.split()[1:]]
            # user nice system idle iowait irq softirq steal
            return vals
        except Exception:
            return None

    def _read_net_dev(self):
        stats = {}
        try:
            with open("/proc/net/dev") as f:
                for line in f.readlines()[2:]:
                    if ":" not in line:
                        continue
                    name, rest = line.split(":", 1)
                    name = name.strip()
                    f_ = rest.split()
                    stats[name] = {
                        "rx_bytes": int(f_[0]),
                        "rx_errs": int(f_[2]),
                        "rx_drop": int(f_[3]),
                        "tx_bytes": int(f_[8]),
                        "tx_errs": int(f_[10]),
                        "tx_drop": int(f_[11]),
                    }
        except Exception:
            pass
        return stats

    def sample(self):
        """Return a dict of delta-based metrics since the previous call."""
        now = time.time()
        elapsed = max(now - self._last_t, 1e-6)

        # --- disk ---
        disk_now = self._read_diskstats()
        write_kb_s = 0.0
        iops = 0.0
        for dev, cur in disk_now.items():
            prev = self._last_disk.get(dev)
            if prev:
                d_sectors = cur["sectors_written"] - prev["sectors_written"]
                d_writes = cur["writes_completed"] - prev["writes_completed"]
                write_kb_s += (d_sectors * 512 / 1024) / elapsed
                iops += d_writes / elapsed
        self._last_disk = disk_now

        # --- irq ---
        irq_now = self._read_irq_total()
        irq_per_s = (irq_now - self._last_irq_total) / elapsed
        self._last_irq_total = irq_now

        # --- iowait % ---
        cpu_now = self._read_cpu_times()
        iowait_pct = None
        if cpu_now and self._last_cpu_times:
            prev = self._last_cpu_times
            d = [c - p for c, p in zip(cpu_now, prev)]
            total = sum(d)
            iowait_pct = round(100 * d[4] / total, 2) if total > 0 else None
        self._last_cpu_times = cpu_now

        # --- network ---
        net_now = self._read_net_dev()
        rx_kb_s = tx_kb_s = 0.0
        rx_drop = tx_drop = 0
        cur_if = net_now.get(self.net_iface)
        prev_if = self._last_net.get(self.net_iface)
        if cur_if and prev_if:
            rx_kb_s = (cur_if["rx_bytes"] - prev_if["rx_bytes"]) / 1024 / elapsed
            tx_kb_s = (cur_if["tx_bytes"] - prev_if["tx_bytes"]) / 1024 / elapsed
            rx_drop = cur_if["rx_drop"] - prev_if["rx_drop"]
            tx_drop = cur_if["tx_drop"] - prev_if["tx_drop"]
        self._last_net = net_now

        self._last_t = now

        return {
            "disk_write_KBs": round(write_kb_s, 2),
            "disk_iops": round(iops, 2),
            "irq_per_s": round(irq_per_s, 2),
            "iowait_pct": iowait_pct,
            "net_iface": self.net_iface,
            "net_rx_KBs": round(rx_kb_s, 2),
            "net_tx_KBs": round(tx_kb_s, 2),
            "net_rx_drop": rx_drop,
            "net_tx_drop": tx_drop,
        }


