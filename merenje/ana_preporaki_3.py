FIELDNAMES = [
    "timestamp", "run_id", "n_cameras", "target_resolution", "target_fps",
    "motion_label", "elapsed_s",
    "camera", "actual_resolution", "cam_fps", "cam_drops", "cam_frame_loss_rate",
    "cam_capture_latency_ms",
    "cpu_pct", "cpu_freq_mhz", "ram_used_mb", "ram_available_mb", "swap_used_mb",
    "process_rss_mb", "temp_c", "throttle",
    "iowait_pct", "disk_write_KBs", "disk_iops", "irq_per_s",
    "net_iface", "net_rx_KBs", "net_tx_KBs", "net_rx_drop", "net_tx_drop",
    "threads",
]


def parse_args():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--cameras", type=str, default="",
                    help="Comma-separated list of RTSP/HTTP camera URLs (1-4).")
    p.add_argument("--mock", action="store_true",
                    help="Use local webcam(s) instead of network cameras, for a dry run.")
    p.add_argument("--run-id", type=str, default=None,
                    help="Identifier for this run, e.g. N2_720p_30fps_dynamic. "
                         "Auto-generated from parameters if omitted.")
    p.add_argument("--target-resolution", type=str, default="unknown",
                    help="Resolution the phone camera app is set to, e.g. 1280x720. "
                         "Recorded as metadata; actual delivered resolution is measured separately.")
    p.add_argument("--target-fps", type=str, default="unknown",
                    help="FPS the phone camera app is set to, e.g. 30.")
    p.add_argument("--motion-label", type=str, required=True,
                    choices=["static", "stochastic", "dynamic"],
                    help="Scene-activity condition staged for this run (mu).")
    p.add_argument("--duration-min", type=float, default=30,
                    help="Run duration in minutes (30 = standard, 240 = thermal stress).")
    p.add_argument("--sample-hz", type=float, default=1.0,
                    help="Sampling frequency in Hz (default 1 Hz per proposal).")
    p.add_argument("--disk-device-prefix", type=str, default="mmcblk",
                    help="Substring to match the storage device in /proc/diskstats "
                         "(mmcblk for SD card, sda for USB/SSD).")
    p.add_argument("--net-iface", type=str, default=None,
                    help="Network interface to measure (default: auto-detect wlan0/eth0).")
    p.add_argument("--output", type=str, required=True, help="Output CSV path.")
    return p.parse_args()


def main():
    args = parse_args()

    if args.mock:
        urls = ["mock-local-webcam"]
    else:
        urls = [u.strip() for u in args.cameras.split(",") if u.strip()]
    if not urls:
        raise SystemExit("No cameras specified. Use --cameras or --mock.")
    if len(urls) > 4:
        raise SystemExit("This study's design matrix caps at 4 concurrent cameras.")

    run_id = args.run_id or (
        f"N{len(urls)}_{args.target_resolution}_{args.target_fps}fps_{args.motion_label}"
    )

    print(f"\n=== Run: {run_id} ===")
    print(f"Cameras ({len(urls)}): {urls}")
    print(f"Target resolution/fps (metadata): {args.target_resolution} / {args.target_fps}")
    print(f"Motion label: {args.motion_label}")
    print(f"Duration: {args.duration_min} min\n")

    cameras = []
    for url in urls:
        print("Connecting:", url)
        cam = ThreadedCamera(url, mock=args.mock)
        if cam.cap.isOpened():
            print("  Connected", cam.resolution)
            cameras.append(cam)
        else:
            print("  FAILED to open", url)

    if not cameras:
        print("No cameras connected. Exiting.")
        return

    sampler = DiskIRQNetSampler(
        disk_device_prefix=args.disk_device_prefix, net_iface=args.net_iface
    )

    out_dir = os.path.dirname(args.output)
    if out_dir:
        os.makedirs(out_dir, exist_ok=True)

    file_exists = os.path.exists(args.output) and os.path.getsize(args.output) > 0
    period = 1.0 / args.sample_hz
    end_time = time.time() + args.duration_min * 60
    start_time = time.time()

    with open(args.output, "a", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=FIELDNAMES)
        if not file_exists:
            writer.writeheader()

        print("Monitoring started. Ctrl+C to stop early.\n")
        try:
            while time.time() < end_time:
                loop_start = time.time()

                cpu_pct = psutil.cpu_percent()
                vm = psutil.virtual_memory()
                sw = psutil.swap_memory()
                sample = sampler.sample()

                shared = {
                    "timestamp": datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
                    "run_id": run_id,
                    "n_cameras": len(cameras),
                    "target_resolution": args.target_resolution,
                    "target_fps": args.target_fps,
                    "motion_label": args.motion_label,
                    "elapsed_s": round(time.time() - start_time, 1),
                    "cpu_pct": cpu_pct,
                    "cpu_freq_mhz": cpu_freq_mhz(),
                    "ram_used_mb": round(vm.used / (1024 * 1024), 1),
                    "ram_available_mb": round(vm.available / (1024 * 1024), 1),
                    "swap_used_mb": round(sw.used / (1024 * 1024), 1),
                    "process_rss_mb": process_rss_mb(),
                    "temp_c": temperature_c(),
                    "throttle": throttle_state(),
                    "iowait_pct": sample["iowait_pct"],
                    "disk_write_KBs": sample["disk_write_KBs"],
                    "disk_iops": sample["disk_iops"],
                    "irq_per_s": sample["irq_per_s"],
                    "net_iface": sample["net_iface"],
                    "net_rx_KBs": sample["net_rx_KBs"],
                    "net_tx_KBs": sample["net_tx_KBs"],
                    "net_rx_drop": sample["net_rx_drop"],
                    "net_tx_drop": sample["net_tx_drop"],
                    "threads": threading.active_count(),
                }

                for cam in cameras:
                    fps, latency_ms = cam.pop_window_stats()
                    row = dict(shared)
                    row.update({
                        "camera": cam.url,
                        "actual_resolution": cam.resolution,
                        "cam_fps": fps,
                        "cam_drops": cam.drops,
                        "cam_frame_loss_rate": cam.frame_loss_rate(),
                        "cam_capture_latency_ms": latency_ms,
                    })
                    writer.writerow(row)

                f.flush()

                print(
                    f"{shared['timestamp']} | run={run_id} | CPU={cpu_pct}% | "
                    f"TEMP={shared['temp_c']} | iowait={shared['iowait_pct']}% | "
                    f"net_rx={shared['net_rx_KBs']}KB/s | "
                    + " | ".join(f"{c.url.split('//')[-1][:15]}:{c.fps}fps" for c in cameras)
                )

                sleep_left = period - (time.time() - loop_start)
                if sleep_left > 0:
                    time.sleep(sleep_left)

        except KeyboardInterrupt:
            print("\nStopped early by user.")

        finally:
            for cam in cameras:
                cam.stop()

    print(f"\nRun complete. Data written to {args.output}")


if __name__ == "__main__":
    main()